import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  AUSTRALIA_ENGINE_UPDATES,
  AUSTRALIA_ENGINE_UPDATE_EVIDENCE,
} from "../src/engine/australia-updates.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const modeLabel = {
  all: "All modes",
  es5: "ES5 Standards",
  es2021: "ECMAScript 2021",
};

const dispositionLabel = {
  diagnostic: "Diagnostic",
  "metadata-only": "Metadata only",
  pending: "Pending",
};

/**
 * @param {import("../src/engine/australia-updates.ts").AustraliaEngineUpdate} update
 */
function pullRequestLinks(update) {
  return update.pullRequests
    .map((number) => `[#${number}](https://github.com/mozilla/rhino/pull/${number})`)
    .join(", ");
}

/**
 * @param {import("../src/engine/australia-updates.ts").AustraliaEngineUpdate} update
 */
function coverage(update) {
  const disposition = update.disposition;
  if (disposition.kind === "pending") return disposition.rationale;
  const features = disposition.featureIds.map((id) => `\`${id}\``).join(", ");
  if (disposition.kind === "metadata-only") {
    return `${features}. ${disposition.rationale}`;
  }
  const rules = disposition.ruleIds.map((id) => `[\`${id}\`](rules/${id}.md)`).join(", ");
  return `${features}; ${rules}. ${disposition.rationale}`;
}

const counts = { diagnostic: 0, "metadata-only": 0, pending: 0 };
/** @type {string[]} */
const pendingEntries = [];
for (const update of AUSTRALIA_ENGINE_UPDATES) {
  counts[update.disposition.kind] += 1;
  if (update.disposition.kind === "pending") {
    pendingEntries.push(
      `- ${pullRequestLinks(update)} — **${update.description}:** ${update.disposition.rationale}`,
    );
  }
}

const rows = AUSTRALIA_ENGINE_UPDATES.map(
  (update) =>
    `| ${pullRequestLinks(update)} | ${update.description} | ${modeLabel[update.mode]} | ${update.updateType === "feature" ? "Feature" : "Fix"} | ${dispositionLabel[update.disposition.kind]} | ${coverage(update)} |`,
).join("\n");

const pending = pendingEntries.join("\n");

const page = `<!-- This file is generated by scripts/generate-australia-engine-docs.mjs. -->
# Australia JavaScript engine update ledger

This ledger is the row-for-row package disposition of ServiceNow's [Australia JavaScript engine update table](${AUSTRALIA_ENGINE_UPDATE_EVIDENCE.url}). It distinguishes implemented diagnostics, deliberately metadata-only behavior, and unfinished investigation. A listed row does not imply that every runtime behavior can or should produce a lint diagnostic.

- Official release label: ${AUSTRALIA_ENGINE_UPDATE_EVIDENCE.officialReleaseLabel}
- Official page updated: ${AUSTRALIA_ENGINE_UPDATE_EVIDENCE.officialUpdatedAt}
- Package review: ${AUSTRALIA_ENGINE_UPDATE_EVIDENCE.reviewedAt}
- Official rows: ${AUSTRALIA_ENGINE_UPDATES.length}
- Diagnostic coverage: ${counts.diagnostic}
- Metadata only: ${counts["metadata-only"]}
- Pending: ${counts.pending}
- Audit complete: ${counts.pending === 0 ? "yes" : "no"}

Pending means the package has not yet established a safe final disposition. Unknown or ambiguous behavior remains silent; it is never counted as supported merely because the row appears here.

| Rhino PR | Official update | Mode | Type | Disposition | Package coverage or next proof |
| --- | --- | --- | --- | --- | --- |
${rows}

## Pending investigations

${pending || "None."}

## Maintenance contract

<code>src/engine/australia-updates.ts</code> is authoritative. Tests pin the official row and pull-request inventory, reject duplicate identities, and verify that completed diagnostic/metadata entries reference real engine capabilities. Run <code>npm run docs</code> after changing a disposition.
`;

await writeFile(join(root, "docs/australia-engine-updates.md"), page);
console.log(
  `updated docs/australia-engine-updates.md (${AUSTRALIA_ENGINE_UPDATES.length} rows, ${counts.pending} pending)`,
);
